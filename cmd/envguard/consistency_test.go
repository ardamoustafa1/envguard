// The rule catalog lives in many places. These tests make sure they all say
// the same thing as the registry, so a new or renamed rule cannot be
// forgotten in the docs.

var (
	catalogRowRE = regexp.MustCompile(`(?m)^\| (EG\d{3}) \| ([a-z-]+) \| ([a-z]+)`)
	ruleIDRE     = regexp.MustCompile(`\bEG\d{3}\b`)
)

func TestRuleCatalogMatchesTheRegistry(t *testing.T) {
	data, err := os.ReadFile(filepath.Join(repoRoot, "CLAUDE.md"))
	if err != nil {
		t.Fatal(err)
	}
	rows := catalogRowRE.FindAllStringSubmatch(string(data), -1)
	all := rules.All()
	if len(rows) != len(all) {
		t.Fatalf("CLAUDE.md lists %d rules, the registry has %d", len(rows), len(all))
	}
	for i, r := range all {
		row := rows[i]
		if row[1] != r.ID() || row[2] != r.Name() || row[3] != r.DefaultSeverity().String() {
			t.Errorf("CLAUDE.md row %d is %s %s %s, registry has %s %s %s", i+1, row[1], row[2], row[3],
				r.ID(), r.Name(), r.DefaultSeverity())
		}
	}

	// `explain --list` shows every rule with its severity.
	var out, errBuf bytes.Buffer
	if code := run([]string{"explain", "--list"}, &out, &errBuf); code != exitOK {
		t.Fatalf("explain --list: exit %d: %s", code, errBuf.String())
	}
	for _, r := range all {
		line := ""
		for _, l := range strings.Split(out.String(), "\n") {
			if strings.HasPrefix(l, r.ID()+" ") {
				line = l
			}
		}
		if line == "" || !strings.Contains(line, r.Name()) || !strings.Contains(line, r.DefaultSeverity().String()) {
			t.Errorf("explain --list line for %s is %q", r.ID(), line)
		}
	}
	// ... and the README table is generated from the same data (see
	// TestReadmeRulesTable).
}

// TestDocsMentionOnlyRealRules: a rule ID in any document must exist.
func TestDocsMentionOnlyRealRules(t *testing.T) {
	known := map[string]bool{}
	last := 0
	for _, r := range rules.All() {
		known[r.ID()] = true
		n, _ := strconv.Atoi(strings.TrimPrefix(r.ID(), "EG"))
		last = max(last, n)
	}
	// CONTRIBUTING.md walks through adding "the next free ID" as an example.
	next := fmt.Sprintf("EG%03d", last+1)
	files := append(docFiles(t), filepath.Join(repoRoot, "CLAUDE.md"), filepath.Join(repoRoot, "CHANGELOG.md"),
		filepath.Join(repoRoot, "SECURITY.md"))
	err := filepath.WalkDir(filepath.Join(repoRoot, ".github"), func(p string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && (strings.HasSuffix(p, ".md") || strings.HasSuffix(p, ".yml")) {
			files = append(files, p)
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	seen := map[string]bool{}
	for _, f := range files {
		if seen[f] {
			continue
		}
		seen[f] = true
		data, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		for _, id := range ruleIDRE.FindAllString(string(data), -1) {
			// Placeholders such as EG999 or EG0NN in examples are fine.
			placeholder := id == "EG999" || id == "EG000" || (id == next && strings.HasSuffix(f, "CONTRIBUTING.md"))
			if !known[id] && !placeholder {
				rel, _ := filepath.Rel(repoRoot, f)
				t.Errorf("%s mentions %s, which is not a rule", filepath.ToSlash(rel), id)
			}
		}
	}
}

// TestEveryCommandHasExamples: --help of every command shows examples.
func TestEveryCommandHasExamples(t *testing.T) {
	root := newRootCmd(buildInfo{Version: "test"})
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		switch c.Name() {
		case "version", "completion", "help":
			// self-explanatory or generated by cobra
		default:
			if strings.TrimSpace(c.Example) == "" {
				t.Errorf("`%s` has no Example in its --help", c.CommandPath())
			}
			if c.Short == "" || c.Long == "" && c.Name() != "version" {
				t.Errorf("`%s` lacks a Short or Long description", c.CommandPath())
			}
		}
		for _, sub := range c.Commands() {
			if !strings.HasPrefix(sub.Name(), "completion") {
				walk(sub)
			}
		}
	}
	walk(root)
}

// TestJSONOutputIsDocumented: every key of the real JSON output appears in
// docs/json-output.md, and the documented schema version is the real one.
func TestJSONOutputIsDocumented(t *testing.T) {
	doc, err := os.ReadFile(filepath.Join(repoRoot, "docs", "json-output.md"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(doc)
	demo := demoRepo(t)
	var keys = map[string]bool{}
	var walk func(v any)
	walk = func(v any) {
		switch x := v.(type) {
		case map[string]any:
			for k, child := range x {
				// Matrix cells and files are keyed by environment name.
				if k != "cells" && k != "files" {
					keys[k] = true
					walk(child)
				}
			}
		case []any:
			for _, child := range x {
				walk(child)
			}
		}
	}
	for _, args := range [][]string{{"check", "--format", "json", "--fail-on", "never"}, {"diff", "--format", "json"},
		{"diff", "staging", "production", "--format", "json"}} {
		var out, errBuf bytes.Buffer
		run(append([]string{"--root", demo}, args...), &out, &errBuf)
		var v any
		if err := json.Unmarshal(out.Bytes(), &v); err != nil {
			t.Fatalf("envguard %s: %v\n%s", strings.Join(args, " "), err, errBuf.String())
		}
		walk(v)
	}
	for k := range keys {
		if !strings.Contains(text, "`"+k+"`") && !strings.Contains(text, `"`+k+`"`) {
			t.Errorf("JSON key %q is not documented in docs/json-output.md", k)
		}
	}
	if !strings.Contains(text, `"schema_version": 1`) || report.SchemaVersion != 1 {
		t.Errorf("docs/json-output.md and report.SchemaVersion (%d) disagree", report.SchemaVersion)
	}
	if len(keys) < 25 {
		t.Errorf("only %d JSON keys collected; the walk is broken", len(keys))
	}
}

var testNameRE = regexp.MustCompile("`(Test[A-Za-z0-9_]+)`")

// TestDocsNameRealTests: a test named in the documentation (the README's
// "Safe by design" table, CONTRIBUTING, SECURITY) must exist, so renaming or
// deleting one cannot leave a promise without its proof.
func TestDocsNameRealTests(t *testing.T) {
	defined := map[string]bool{}
	defRE := regexp.MustCompile(`(?m)^func (Test[A-Za-z0-9_]+)\(`)
	err := filepath.WalkDir(repoRoot, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (d.Name() == "node_modules" || d.Name() == ".git" || d.Name() == "dist") {
			return filepath.SkipDir
		}
		if !d.IsDir() && strings.HasSuffix(p, "_test.go") {
			data, err := os.ReadFile(p) //nolint:gosec // test
			if err != nil {
				return err
			}
			for _, m := range defRE.FindAllSubmatch(data, -1) {
				defined[string(m[1])] = true
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	named := 0
	for _, name := range []string{"README.md", "CONTRIBUTING.md", "SECURITY.md", "CLAUDE.md"} {
		data, err := os.ReadFile(filepath.Join(repoRoot, name))
		if err != nil {
			continue
		}
		for _, m := range testNameRE.FindAllStringSubmatch(string(data), -1) {
			named++
			if !defined[m[1]] {
				t.Errorf("%s names the test %s, which does not exist", name, m[1])
			}
		}
	}
	if named < 8 {
		t.Errorf("only %d tests are named in the docs; is the pattern broken?", named)
	}
}
